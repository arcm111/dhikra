"""The app icon: an eight-pointed star (two squares, a point at the top) drawn as a gold outline,
holding a gold open book, on the app's dark green. One colour, no fine detail, so it stays clean
down to the smallest launcher sizes.

Writes the adaptive icon's layers (drawable/ic_launcher_{foreground,background,monochrome}.xml),
the status bar icon (drawable/ic_notification.xml), the pre-Android 8 launcher icons
(mipmap-*/ic_launcher{,_round}.webp) and, optionally, a preview sheet:

    python3 scripts/logo/rosette.py app/src/main/res [preview.png]

Every shape is a polygon in the adaptive icon's 108 × 108 viewport, drawn the same way in the
vector drawables and in the raster icons. The mark keeps within the 66 dp safe zone (radius 33).
"""
import math
import sys

from PIL import Image, ImageDraw

C = 54.0
GOLD = (226, 196, 120)
GOLD_HEX = "#FFE2C478"
BG_TOP, BG_BOTTOM = (31, 94, 67), (14, 49, 34)


def star8(R):
    """The eight-pointed star of two squares, a point at the top."""
    r = R * math.cos(math.pi / 4) / math.cos(math.pi / 8)
    return [(C + (R if i % 2 == 0 else r) * math.cos(-math.pi / 2 + math.pi * i / 8),
             C + (R if i % 2 == 0 else r) * math.sin(-math.pi / 2 + math.pi * i / 8)) for i in range(16)]


def inset(poly, w):
    """[poly] moved inward by [w], its corners mitred: the inner edge of an outline [w] thick."""
    n = len(poly)
    area = sum(poly[i][0] * poly[(i + 1) % n][1] - poly[(i + 1) % n][0] * poly[i][1] for i in range(n))
    sign = 1 if area > 0 else -1
    lines = []
    for i in range(n):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        nx, ny = -dy / length * sign, dx / length * sign
        lines.append(((x1 + nx * w, y1 + ny * w), (dx, dy)))
    out = []
    for i in range(n):
        (p, d), (q, e) = lines[i - 1], lines[i]
        t = ((q[0] - p[0]) * e[1] - (q[1] - p[1]) * e[0]) / (d[0] * e[1] - d[1] * e[0])
        out.append((p[0] + d[0] * t, p[1] + d[1] * t))
    return out


def quad(p0, p1, p2, n=20):
    """Points along a quadratic curve from p0 to p2 (p1 its control), p0 excluded."""
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in (i / n for i in range(1, n + 1))]


def book(w=13.0, h=15.0, gap=1.4, lift=2.6, sag=1.8, cy=55.0):
    """The two pages of an open book, solid, the tops rising from the spine to the outer corners."""
    top, bottom = cy - h / 2 + lift * 0.4, cy + h / 2
    x0, x1 = C - gap, C - gap - w
    left = [(x0, top)] + quad((x0, top), ((x0 + x1) / 2, top - lift), (x1, top - lift * 0.6))
    left += [(x1, bottom - sag - lift * 0.6)] + quad((x1, bottom - sag - lift * 0.6), ((x0 + x1) / 2, bottom - sag - lift), (x0, bottom - sag * 0.1))
    return left, [(2 * C - x, y) for x, y in left]


# The mark's size: launchers crop the adaptive icon well inside its 66dp safe zone (Samsung's
# squircle shows little more than the centre 66), so the star keeps a clear margin round it.
SCALE = 0.78
R = 32.0 * SCALE


def scaled(poly):
    return [(C + (x - C) * SCALE, C + (y - C) * SCALE) for x, y in poly]


STAR = star8(R)
STAR_INNER = inset(STAR, 3.0)
PAGE_L, PAGE_R = (scaled(page) for page in book())


# ---------------------------------------------------------------- The vector drawables

def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def path(*polys):
    return " ".join("M" + " L".join(f"{f(x)},{f(y)}" for x, y in poly) + "Z" for poly in polys)


HEAD = '''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">'''


def mark(color, indent="    "):
    """The star's outline (its outer and inner edges, filled even-odd) and the book's pages."""
    return "\n".join([
        f'{indent}<path\n{indent}    android:fillColor="{color}"\n{indent}    android:fillType="evenOdd"\n'
        f'{indent}    android:pathData="{path(STAR, STAR_INNER)}" />',
        f'{indent}<path\n{indent}    android:fillColor="{color}"\n{indent}    android:pathData="{path(PAGE_L, PAGE_R)}" />',
    ])


FOREGROUND = f'''{HEAD}
    <!-- Dhikra mark: an eight-pointed star outline holding an open book, in gold. Inside the 66dp
         adaptive safe zone; generated by scripts/logo/rosette.py. -->
{mark(GOLD_HEX)}
</vector>
'''

MONOCHROME = f'''{HEAD}
    <!-- Single-colour version of the mark for Android 13+ themed app icons. -->
{mark("#FFFFFFFF")}
</vector>
'''

# The status bar's icon: the mark filling the icon (the square round the star).
HALF = math.ceil(R) + 1
NOTIFICATION = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The app's mark as the monochrome notification icon: generated by scripts/logo/rosette.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{2 * HALF}"
    android:viewportHeight="{2 * HALF}">
    <group android:translateX="{HALF - 54}" android:translateY="{HALF - 54}">
{mark("#FFFFFFFF", indent="        ")}
    </group>
</vector>
'''

BACKGROUND = HEAD + '''
    <!-- The app's dark green, a little lighter at the top. -->
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54"
                android:startY="0"
                android:endX="54"
                android:endY="108">
                <item android:color="#FF1F5E43" android:offset="0" />
                <item android:color="#FF0E3122" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''


# ---------------------------------------------------------------- The raster icons

def icon(size, shape="circle", ss=4):
    S = size * ss
    s = S / 108
    img = Image.new("RGB", (S, S))
    d = ImageDraw.Draw(img)
    for y in range(S):
        t = y / (S - 1)
        d.line([(0, y), (S, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(BG_TOP, BG_BOTTOM)))
    mask = Image.new("L", (S, S), 0)
    md = ImageDraw.Draw(mask)
    md.polygon([(x * s, y * s) for x, y in STAR], fill=255)
    md.polygon([(x * s, y * s) for x, y in STAR_INNER], fill=0)
    for page in (PAGE_L, PAGE_R):
        md.polygon([(x * s, y * s) for x, y in page], fill=255)
    img.paste(Image.new("RGB", (S, S), GOLD), (0, 0), mask)

    clip = Image.new("L", (S, S), 0)
    cd = ImageDraw.Draw(clip)
    if shape == "circle":
        cd.ellipse([0, 0, S - 1, S - 1], fill=255)
    elif shape == "square":
        cd.rectangle([0, 0, S, S], fill=255)
    else:
        cd.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.23), fill=255)
    out = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    out.paste(img, (0, 0), clip)
    return out.resize((size, size), Image.LANCZOS)


def legacy(size, shape):
    """A pre-Android 8 launcher icon: the central 72/108 of the adaptive icon, masked to [shape]."""
    full = icon(round(size * 108 / 72), "square")
    off = (full.width - size) // 2
    crop = full.crop((off, off, off + size, off + size))
    S = size * 4
    mask = Image.new("L", (S, S), 0)
    md = ImageDraw.Draw(mask)
    if shape == "circle":
        md.ellipse([0, 0, S - 1, S - 1], fill=255)
    else:
        md.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.2), fill=255)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(crop, (0, 0), mask.resize((size, size), Image.LANCZOS))
    return out


if __name__ == "__main__":
    res = sys.argv[1]
    for name, text in [("ic_launcher_foreground", FOREGROUND), ("ic_launcher_monochrome", MONOCHROME),
                       ("ic_launcher_background", BACKGROUND), ("ic_notification", NOTIFICATION)]:
        open(f"{res}/drawable/{name}.xml", "w").write(text)
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        legacy(size, "squircle").save(f"{res}/mipmap-{density}/ic_launcher.webp", "WEBP", lossless=True)
        legacy(size, "circle").save(f"{res}/mipmap-{density}/ic_launcher_round.webp", "WEBP", lossless=True)
    if len(sys.argv) > 2:
        sheet = Image.new("RGBA", (980, 420), (249, 247, 242, 255))
        sheet.alpha_composite(icon(320, "circle"), (20, 50))
        sheet.alpha_composite(icon(320, "squircle"), (360, 50))
        for i, sz in enumerate((96, 48)):
            sheet.alpha_composite(icon(sz, "circle"), (720 + i * 120, 120))
        dark = Image.new("RGBA", (240, 110), (16, 20, 18, 255))
        dark.alpha_composite(icon(72, "circle"), (20, 20))
        dark.alpha_composite(icon(48, "squircle"), (130, 32))
        sheet.alpha_composite(dark, (720, 260))
        sheet.save(sys.argv[2])
