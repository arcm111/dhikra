import sys, geom as g
res = sys.argv[1]
crescent, _, _ = g.crescent_path()
beads = "".join(g.bead_path(c) for c in g.BEADS)
HEAD = '''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">'''

def gold(path):
    return f'''    <path android:pathData="{path}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54"
                android:startY="36"
                android:endX="54"
                android:endY="82">
                <item android:color="#FFE8D28A" android:offset="0" />
                <item android:color="#FFC2A043" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>'''

def arch(color):
    return f'''    <path
        android:pathData="{g.arch_path()}"
        android:strokeColor="{color}"
        android:strokeWidth="{g.f(g.STROKE)}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />'''

fg = f'''{HEAD}
    <!-- Dhikra mark: a mihrab arch holding a crescent and a star, standing on three prayer beads
         (the steps of the day). Drawn inside the 66dp adaptive safe zone; geometry generated by
         scripts/logo/geom.py. -->
{arch("#FFF7F0DF")}
{gold(crescent)}
{gold(g.star_path())}
{gold(beads)}
</vector>
'''
mono = f'''{HEAD}
    <!-- Single-colour version of the mark for Android 13+ themed app icons. -->
{arch("#FFFFFFFF")}
    <path android:fillColor="#FFFFFFFF" android:pathData="{crescent}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="{g.star_path()}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="{beads}" />
</vector>
'''
bg = f'''{HEAD}
    <!-- Dark green with a soft light from the top-left. -->
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="8"
                android:startY="0"
                android:endX="100"
                android:endY="108">
                <item android:color="#FF1F5E43" android:offset="0" />
                <item android:color="#FF174B35" android:offset="0.55" />
                <item android:color="#FF0E3122" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="30"
                android:centerY="18"
                android:gradientRadius="70">
                <item android:color="#2EFFFFFF" android:offset="0" />
                <item android:color="#00FFFFFF" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
for name, text in [("ic_launcher_foreground", fg), ("ic_launcher_monochrome", mono), ("ic_launcher_background", bg)]:
    open(f"{res}/drawable/{name}.xml", "w").write(text)
